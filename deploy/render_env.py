#!/usr/bin/env python3
"""Merge the host's configuration sources into the .env file Docker Compose reads (stdlib only).

    render_env.py CONFIG_JSON APP_SECRET_JSON DB_SECRET_JSON HOST_ENV --pem-out PATH > .env

- CONFIG_JSON      non-secret settings (SSM parameter written by Terraform)
- APP_SECRET_JSON  DJANGO_SECRET_KEY, MONGO_URL, CLOUDFRONT_PRIVATE_KEY, optional SENTRY_DSN (Secrets Manager)
- DB_SECRET_JSON   {"username", "password"} (RDS-managed secret)
- HOST_ENV         KEY=VALUE lines written at first boot (environment, registry, log group...)

The CloudFront private key is multi-line, so it is written to --pem-out (mounted into the API container)
instead of the env file. Exits non-zero, naming what is missing, if a required setting is absent.
"""

import argparse
import json
import os
import sys

REQUIRED = [
    "DJANGO_SETTINGS_MODULE", "DJANGO_SECRET_KEY", "DJANGO_ALLOWED_HOSTS", "POSTGRES_HOST", "POSTGRES_DB",
    "POSTGRES_USER", "POSTGRES_PASSWORD", "KAFKA_BOOTSTRAP_SERVERS", "MONGO_URL", "S3_BUCKET", "CDN_BASE_URL",
    "CLOUDFRONT_KEY_PAIR_ID", "AWS_REGION", "ECR_REGISTRY", "LOG_GROUP", "ENVIRONMENT",
]  # fmt: skip


def read_host_env(path):
    values = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    return values


def quote(value):
    """Double-quote for Docker Compose: escape backslashes and quotes, and $ as $$ (Compose interpolates $).

    Verified against a real container: values with ' " $ ${...} # \\ and spaces arrive unchanged. (Note that
    `docker compose config` *prints* $ as $$; that is its own output escaping, not the container's value.)
    """
    text = str(value)
    if "\n" in text or "\r" in text:
        raise ValueError("multi-line values can't go in an env file")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$") + '"'


def merge(config, app_secret, db_secret, host_env):
    values = {**config, **host_env}
    for key in ("DJANGO_SECRET_KEY", "MONGO_URL", "SENTRY_DSN"):
        if app_secret.get(key):
            values[key] = app_secret[key]
    values["POSTGRES_USER"] = db_secret.get("username", "")
    values["POSTGRES_PASSWORD"] = db_secret.get("password", "")
    return values


def render(values):
    lines = ["# Generated by deploy/render_env.py on each deploy. Do not edit: changes are overwritten."]
    lines += [f"{key}={quote(value)}" for key, value in sorted(values.items())]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("config")
    parser.add_argument("app_secret")
    parser.add_argument("db_secret")
    parser.add_argument("host_env")
    parser.add_argument("--pem-out", required=True)
    args = parser.parse_args(argv)

    def load(path):
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)

    app_secret = load(args.app_secret)
    values = merge(load(args.config), app_secret, load(args.db_secret), read_host_env(args.host_env))

    missing = [key for key in REQUIRED if not values.get(key)]
    pem = app_secret.get("CLOUDFRONT_PRIVATE_KEY", "")
    if "PRIVATE KEY" not in pem:
        missing.append("CLOUDFRONT_PRIVATE_KEY (PEM) in the app secret")
    if missing:
        print("render_env: missing settings: " + ", ".join(missing), file=sys.stderr)
        return 1

    fd = os.open(args.pem_out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o400)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(pem.strip() + "\n")
    sys.stdout.write(render(values))
    return 0


if __name__ == "__main__":
    sys.exit(main())
