"""The save SQL against real Postgres (same approach as test_db_claim.py)."""

import uuid

import psycopg
import pytest

from encoder import config
from ml.db import AnalysisDatabase, VideoGone
from ml.tagging import Tag
from ml.transcribe import Cue, Transcript

SCHEMA = """
CREATE TEMP TABLE videos_video (id uuid PRIMARY KEY);
CREATE TEMP TABLE video_transcripts (
    video_id uuid PRIMARY KEY REFERENCES videos_video(id) ON DELETE CASCADE,
    language varchar(10), text text, subtitles_key varchar(512), model varchar(50), event_id varchar(64),
    created_at timestamptz
);
CREATE TEMP TABLE video_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id uuid REFERENCES videos_video(id) ON DELETE CASCADE,
    tag varchar(50), kind varchar(20), confidence double precision, source varchar(20),
    UNIQUE (video_id, tag, kind)
);
"""
SPEECH = Transcript("en", (Cue(0, 1, "Hello"), Cue(1, 2, "world")))


@pytest.fixture
def db():
    try:
        database = AnalysisDatabase(config.DATABASE)
        database._connection().execute(SCHEMA)
    except psycopg.OperationalError:
        pytest.skip("needs Postgres")
    yield database
    database.conn.close()


@pytest.fixture
def video_id(db):
    value = str(uuid.uuid4())
    db._connection().execute("INSERT INTO videos_video VALUES (%s)", (value,))
    return value


def rows(db, sql, *args):
    return db._connection().execute(sql, args).fetchall()


def test_save_then_a_redelivery_is_recognised(db, video_id):
    assert db.already_analysed(video_id, "e1") is False
    db.save(video_id, "e1", SPEECH, "hls/x/subtitles/en.vtt", [Tag("animals", "topic", 0.8)])
    assert db.already_analysed(video_id, "e1") is True
    assert db.already_analysed(video_id, "e2") is False
    assert rows(db, "SELECT language, text, subtitles_key FROM video_transcripts")[0] == (
        "en",
        "Hello world",
        "hls/x/subtitles/en.vtt",
    )


def test_analysing_again_replaces_clip_tags_but_keeps_manual_ones(db, video_id):
    db.save(video_id, "e1", SPEECH, "", [Tag("animals", "topic", 0.8), Tag("cars", "topic", 0.5)])
    db._connection().execute(
        "INSERT INTO video_tags (video_id, tag, kind, confidence, source) VALUES (%s, 'cooking', 'topic', 1, 'manual')",
        (video_id,),
    )
    db.save(video_id, "e2", SPEECH, "", [Tag("cooking", "topic", 0.6), Tag("nature", "topic", 0.5)])
    assert sorted(rows(db, "SELECT tag, source FROM video_tags")) == [("cooking", "manual"), ("nature", "clip")]
    assert rows(db, "SELECT event_id FROM video_transcripts") == [("e2",)]


def test_a_deleted_video_is_reported_and_leaves_nothing_behind(db):
    with pytest.raises(VideoGone):
        db.save(str(uuid.uuid4()), "e1", SPEECH, "", [])
    assert rows(db, "SELECT count(*) FROM video_transcripts") == [(0,)]
    # The connection is still usable afterwards.
    assert rows(db, "SELECT 1") == [(1,)]


def test_a_failed_tag_rolls_back_the_transcript(db, video_id):
    too_long = Tag("x" * 60, "topic", 0.5)
    with pytest.raises(psycopg.errors.StringDataRightTruncation):
        db.save(video_id, "e1", SPEECH, "", [too_long])
    assert db.already_analysed(video_id, "e1") is False
